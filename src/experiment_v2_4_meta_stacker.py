"""
src/experiment_v2_4_meta_stacker.py
===================================

EXPERIMENT 4 (prompt priority 4)
---------------------------------
OOF meta-stacker: a small LogisticRegression on

    [ text_probs (3 cols), id_probs (3 cols), hand-crafted features (9 cols) ]

with y as target, itself validated with the SAME grouped 5-fold split
(StratifiedGroupKFold(5, shuffle=True, random_state=42), group =
clean_text.lower().strip()). The OOF base probabilities come from the existing
per-fold loop, so the meta-learner is never trained and evaluated on the same
fold's rows.

Two variants are reported:

A. `spec`      -- exactly the prompt's protocol: base OOF matrices from the
                  single per-fold loop, meta-learner cross-fitted with its own
                  grouped 5-fold CV.
B. `strict`    -- an extra, more conservative check in which the meta-TRAIN rows'
                  base features are regenerated by base models that never saw
                  the meta-evaluation fold either (a genuinely double-nested
                  loop, 20 extra text fits). A row's own label still never
                  reaches its own prediction in either variant; variant B also
                  removes the milder "base model saw the eval fold" optimism.

Ablations reported for free: probs-only (no hand features), hand-features-only,
single feature group, and the raw 2-source blend for reference.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import experiment_v2_harness as H
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.preprocessing import StandardScaler

META_KW = dict(C=1.0, max_iter=2000, class_weight="balanced", random_state=H.SEED)
META_FEATURES = ([f"text_p{c}" for c in H.CLASSES] + [f"id_p{c}" for c in H.CLASSES]
                 + H.HAND_FEATURE_NAMES)


def meta_folds(y, clean_texts):
    """The SAME grouped 5-fold split, recomputed through its own call and
    asserted to equal the outer fold ids."""
    keys = pd.Index([H.group_key(t) for t in clean_texts], dtype="object")
    groups = pd.factorize(keys, sort=False)[0]
    sgkf = StratifiedGroupKFold(n_splits=H.N_SPLITS, shuffle=True, random_state=H.SEED)
    fold_ids = np.full(len(y), -1, dtype=int)
    for k, (_tr, va) in enumerate(sgkf.split(np.zeros(len(y)), y, groups)):
        fold_ids[va] = k
    return fold_ids


def cross_fitted_meta(X, y, fold_ids, tag, cols_note=""):
    """Meta-learner trained on 4 folds of OOF rows, scored on the held-out fold."""
    pred = np.zeros(len(y), dtype=int)
    coefs = []
    for k in range(H.N_SPLITS):
        tr, va = H.fold_split(fold_ids, k)
        sc = StandardScaler().fit(X[tr])          # scaler sees TRAIN rows only
        A, B = sc.transform(X[tr]).astype(np.float64), sc.transform(X[va]).astype(np.float64)
        clf = LogisticRegression(**META_KW).fit(A, y[tr])
        pred[va] = clf.predict(B)
        coefs.append({"fold": k, "n_meta_train": int(len(tr)),
                      "intercept": [round(float(v), 4) for v in clf.intercept_],
                      "coef": [round(float(v), 4) for v in clf.coef_[0]]})
    f1_pooled = float(H.f1_score(y, pred, average="macro", labels=list(H.CLASSES),
                                 zero_division=0))
    per_fold = []
    for k in range(H.N_SPLITS):
        _, va = H.fold_split(fold_ids, k)
        per_fold.append({
            "fold": k, "n_val": int(len(va)),
            "f1": round(float(H.f1_score(y[va], pred[va], average="macro",
                                         labels=list(H.CLASSES), zero_division=0)), 6),
        })
    std = float(np.std([r["f1"] for r in per_fold]))
    print(f"{tag:34s} pooled OOF = {f1_pooled:.6f} | delta vs {H.BASELINE_OOF_F1:.6f} = "
          f"{f1_pooled - H.BASELINE_OOF_F1:+.6f} | fold std {std:.6f} {cols_note}")
    return {"tag": tag, "pooled_oof_macro_f1": f1_pooled,
            "delta_vs_baseline": f1_pooled - H.BASELINE_OOF_F1,
            "per_class_f1": H.per_class_f1(y, pred),
            "per_fold": per_fold, "fold_macro_f1_std": std,
            "fold_models": coefs, "feature_names": META_FEATURES[: X.shape[1]]}


def strict_nested_base(y, ids, clean_texts, fold_ids, oof_text, oof_id):
    """Double-nested base features: for meta-eval fold k, the meta-train rows
    get base predictions from models that saw NEITHER their own fold NOR k."""
    n = len(y)
    P_text = np.zeros((n, 3))
    P_id = np.zeros((n, 3))
    t0 = time.time()
    for k in range(H.N_SPLITS):
        _, va = H.fold_split(fold_ids, k)
        # eval rows: base model trained on everything except fold k (= the EXP 0 OOF)
        P_text[va], P_id[va] = oof_text[va], oof_id[va]
        for j in range(H.N_SPLITS):
            if j == k:
                continue
            tr = np.flatnonzero((fold_ids != j) & (fold_ids != k))
            vj = np.flatnonzero(fold_ids == j)
            assert len(tr) + len(vj) + len(va) == n
            word, char = H.fit_vectorizers(clean_texts[tr])
            A = H.matrix_from(word, char, clean_texts[tr])
            B = H.matrix_from(word, char, clean_texts[vj])
            del word, char
            clf = H.fit_text_lr(A, y[tr])
            P_text[vj] = clf.predict_proba(B)
            del A, B, clf
            # restricted prior pool: no fold-k rows, no fold-j rows
            P_id[vj] = H.id_prior(ids[vj], ids[tr], y[tr], tag=f"strict_f{k}_f{j}")
        print(f"  strict fold{k} done ({time.time() - t0:.0f}s elapsed)")
    return P_text, P_id


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--text-source", default="lr", choices=["lr", "ens"])
    ap.add_argument("--skip-strict", action="store_true")
    args = ap.parse_args()
    t_start = time.time()

    H.banner("EXP 4 -- OOF meta-stacker (nested grouped CV)")
    d = H.load_data()
    y, ids, clean_texts, raw = d["y"], d["ids"], d["clean_texts"], d["train"]["text"].to_numpy()

    anchor = np.load(H.PRED_DIR / "v2_0_baseline_anchor_oof.npz")
    fold_ids, oof_id = anchor["fold_ids"], anchor["oof_id"]
    oof_text = anchor["oof_text"]
    if args.text_source == "ens":
        e = np.load(H.PRED_DIR / "v2_1_text_ensemble_oof.npz")
        oof_text, oof_id = e["oof_ens"], e["oof_id"]

    mf = meta_folds(y, clean_texts)
    assert np.array_equal(mf, fold_ids), "meta CV split != outer grouped split"
    print("meta-learner's own grouped CV split == outer grouped split (asserted)")

    Hraw = H.hand_feature_matrix(raw)
    print(f"text source: {args.text_source} | text-only OOF F1 = "
          f"{H.macro_f1(y, oof_text):.6f} | id-only = {H.macro_f1(y, oof_id):.6f} | "
          f"reference blend@0.40 = "
          f"{H.macro_f1(y, H.blend(oof_text, oof_id, H.ALPHA_BASELINE)):.6f}")

    specs = {
        "text+id+hand (spec)": np.hstack([oof_text, oof_id, Hraw]),
        "text+id (no hand)": np.hstack([oof_text, oof_id]),
        "text+hand (no id)": np.hstack([oof_text, Hraw]),
        "id+hand (no text)": np.hstack([oof_id, Hraw]),
    }
    results = []
    for tag, X in specs.items():
        results.append(cross_fitted_meta(X, y, fold_ids, f"[spec] {tag}"))

    strict = None
    if not args.skip_strict:
        print("\n-- strict double-nested base features (20 extra text fits) --")
        s_text, s_id = strict_nested_base(y, ids, clean_texts, fold_ids,
                                          oof_text, oof_id)
        X = np.hstack([s_text, s_id, Hraw])
        strict = cross_fitted_meta(X, y, fold_ids, "[strict] text+id+hand")
        strict["reference_blend_0.40_on_strict_base"] = round(
            H.macro_f1(y, H.blend(s_text, s_id, H.ALPHA_BASELINE)), 6)
        print(f"{'  [strict] reference blend@0.40':34s} = "
              f"{strict['reference_blend_0.40_on_strict_base']:.6f}")
        np.savez_compressed(H.CACHE_DIR / "strict_base_probs.npz",
                            oof_text=s_text, oof_id=s_id, fold_ids=fold_ids)

    headline = results[0]
    payload = {
        "experiment": "v2_4_meta_stacker",
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "python": sys.version.split()[0], "seed": H.SEED,
        "text_source": args.text_source,
        "validation": {"method": "StratifiedGroupKFold", "n_splits": H.N_SPLITS,
                       "shuffle": True, "random_state": H.SEED,
                       "group_key": "clean_text.lower().strip()",
                       "metric": "pooled OOF macro F1"},
        "meta_learner": {"model": "LogisticRegression", **META_KW,
                         "scaler": "StandardScaler fitted on meta-train rows only",
                         "features": META_FEATURES,
                         "note": "base features are the grouped OOF probabilities; "
                                 "meta-learner cross-fitted with its own grouped CV"},
        "results": results,
        "strict_nested": strict,
        "baseline_oof_f1": H.BASELINE_OOF_F1,
        "delta_vs_baseline_headline": headline["delta_vs_baseline"],
        "beats_baseline": bool(headline["delta_vs_baseline"] > 0),
        "runtime_seconds": round(time.time() - t_start, 1),
    }
    H.save_result("4_meta_stacker", payload)
    print(f"\nheadline (spec, text+id+hand): {headline['pooled_oof_macro_f1']:.6f} "
          f"| delta {headline['delta_vs_baseline']:+.6f} | beats baseline: "
          f"{payload['beats_baseline']} | runtime {payload['runtime_seconds']}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
